// Real Electron + isolated backend for defaults; generation requests intercepted before AI calls.
import assert from 'node:assert/strict'
import { launchApp, report, mockJson, API } from './harness.mjs'

const t = report()
const { app, page, shot, jsErrors } = await launchApp({ name: 'recap-prompts' })
try {
  const initial = await (await fetch(`${API}/api/recap/prompts`)).json()
  await fetch(`${API}/api/recap/prompts`, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(initial.originals) })
  await page.route('**/api/voices', route => mockJson(route, { voices: [{ voice_id: 'review', name: 'review' }] }))
  await page.route('**/api/bgm', route => mockJson(route, []))
  let singleBody = '', batchBody = null
  await page.route('**/api/recap/run', route => { singleBody = route.request().postData() || ''; return mockJson(route, { detail: 'E2E: generation intercepted' }, 409) })
  await page.route('**/api/recap/batch', route => { batchBody = route.request().postDataJSON(); return mockJson(route, { detail: 'E2E: generation intercepted' }, 409) })
  await page.waitForLoadState('domcontentloaded')
  await page.evaluate(() => localStorage.setItem('yt_workflow_audio_config', JSON.stringify({ voiceId: 'review', bgmEnabled: false })))
  await page.getByText('Recap & Audio', { exact: true }).first().click()
  const panel = page.getByRole('region', { name: 'Prompt tạo nội dung' })
  const editor = panel.locator('textarea')
  const base = await (await fetch(`${API}/api/recap/prompts`)).json()
  await editor.waitFor()
  assert.equal(await editor.inputValue(), base.originals.script)
  t.ok('mở sẵn toàn bộ prompt gốc từ backend', true)
  const script = base.originals.script + '\nE2E: Kể chuyện công nghệ, tránh từ ngữ ẩm thực.'
  const caption = base.originals.caption + '\nE2E: hashtag công nghệ.'
  await editor.fill(script)
  await panel.getByRole('tab', { name: 'Tiêu đề, mô tả & hashtag' }).click()
  await editor.fill(caption)
  await panel.getByRole('tab', { name: 'Kịch bản & lời bình' }).click()
  assert.equal(await editor.inputValue(), script)
  t.ok('đổi tab giữ các chỉnh sửa độc lập', true)
  const saved = page.waitForResponse(r => r.url().endsWith('/api/recap/prompts') && r.request().method() === 'PUT')
  await panel.getByRole('button', { name: 'Lưu làm mặc định' }).click()
  assert.equal((await saved).status(), 200)
  await page.reload()
  await page.getByText('Recap & Audio', { exact: true }).first().click()
  await editor.waitFor()
  assert.equal(await editor.inputValue(), script)
  t.ok('lưu mặc định và tải lại app vẫn giữ prompt', true)
  await editor.fill('prompt thiếu các biến bắt buộc')
  assert.equal(await page.getByRole('button', { name: 'Bắt đầu tạo recap video', exact: true }).isDisabled(), true)
  assert.equal(await panel.getByRole('button', { name: 'Lưu làm mặc định' }).isDisabled(), true)
  t.ok('prompt không hợp lệ chặn chạy và lưu', true)
  await editor.fill(script)
  await panel.getByRole('tab', { name: 'Tiêu đề, mô tả & hashtag' }).click()
  await panel.getByRole('button', { name: 'Khôi phục prompt gốc' }).click()
  assert.equal(await editor.inputValue(), base.originals.caption)
  await panel.getByRole('tab', { name: 'Kịch bản & lời bình' }).click()
  assert.equal(await editor.inputValue(), script)
  t.ok('khôi phục chỉ tab đang chọn, giữ prompt còn lại', true)
  await page.getByPlaceholder('https://www.youtube.com/watch?v=...', { exact: true }).fill('https://www.youtube.com/watch?v=abcdefghijk')
  await page.getByRole('button', { name: 'Bắt đầu tạo recap video', exact: true }).click()
  await page.getByText('E2E: generation intercepted', { exact: true }).waitFor()
  const multipartText = singleBody.replace(/\r\n/g, '\n')
  assert.ok(multipartText.includes(script) && multipartText.includes(base.originals.caption))
  t.ok('đơn lẻ gửi cả hai prompt đang sửa, không cần lưu', true)
  await page.getByRole('button', { name: /Hàng loạt \(Queue/ }).click()
  await page.locator('.batch-panel textarea, textarea.raw-input').last().fill('https://www.youtube.com/watch?v=abcdefghijk')
  await page.locator('#btn-batch-submit').click()
  await page.getByText('E2E: generation intercepted', { exact: true }).waitFor()
  assert.equal(batchBody.prompts.script, script)
  assert.equal(batchBody.prompts.caption, base.originals.caption)
  t.ok('hàng loạt dùng cùng bản prompt đang sửa', true)
  await shot('recap-prompts-desktop')
  await page.setViewportSize({ width: 1000, height: 850 })
  assert.equal(await panel.evaluate(el => el.scrollWidth <= el.clientWidth + 1), true)
  await shot('recap-prompts-compact')
  t.ok('khối prompt không tràn ngang khi thu cửa sổ', true)
  assert.deepEqual(jsErrors(), [])
  t.ok('không có lỗi JavaScript', true)
} catch (error) {
  t.ok('kịch bản hoàn tất', false, String(error))
  await shot('recap-prompts-error').catch(() => {})
  throw error
} finally {
  await app.close()
  t.done()
}
